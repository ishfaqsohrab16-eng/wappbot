export const OPS = ["count", "count_by", "list", "details", "sum", "avg", "top", "current", "help"];

/**
 * Check every entity against the live schema; drop the ones whose tables or
 * columns are missing so the catalogue can never reference invented fields.
 */
export function activeEntities(schema) {
  const out = {};
  const problems = [];
  for (const [name, e] of Object.entries(ENTITIES)) {
    // alias -> table, from "table alias" pairs in FROM/JOIN and sub-queries
    const aliases = new Map();
    const sources = [e.from, ...Object.values(e.filters || {}), e.top?.join || ""].join(" ");
    for (const m of sources.matchAll(/(?:from|join)\s+`?([a-z_]+)`?\s+(?:as\s+)?([a-z][a-z0-9_]*)/gi)) aliases.set(m[2], m[1]);
    for (const m of e.from.matchAll(/^`?([a-z_]+)`?\s+([a-z][a-z0-9_]*)/gi)) aliases.set(m[2], m[1]);
    const colOk = (ref) => {
      const [alias, col] = ref.split(".");
      const t = schema.tables.get(aliases.get(alias));
      return Boolean(t && t.columns.some((c) => c.name === col));
    };
    const refsIn = (s) => [...String(s).matchAll(/\b([a-z][a-z0-9_]*)\.([a-z_][a-z0-9_]*)\b/gi)].map((m) => `${m[1]}.${m[2]}`);

    const core = [e.from, e.key, e.date, e.sum, ...Object.values(e.filters || {}), ...Object.values(e.idents || {}), e.student?.col];
    const tablesOk = [...aliases.values()].every((t) => schema.tables.has(t));
    const missingCore = tablesOk ? core.filter(Boolean).flatMap(refsIn).filter((r) => aliases.has(r.split(".")[0]) && !colOk(r)) : ["tables"];
    if (missingCore.length) {
      problems.push(`${name}: missing ${[...new Set(missingCore)].join(", ")}`);
      continue;
    }
    // Display-only columns: drop the ones that do not exist instead of failing.
    const keep = (expr) => refsIn(expr).every(colOk);
    const copy = { ...e, list: (e.list || []).filter(keep), details: (e.details || e.list || []).filter(keep) };
    if (e.avg) copy.avg = Object.fromEntries(Object.entries(e.avg).filter(([, c]) => keep(c)));
    if (e.top && !(keep(e.top.by) && keep(e.top.label))) delete copy.top;
    out[name] = copy;
  }
  return { entities: out, problems };
}
